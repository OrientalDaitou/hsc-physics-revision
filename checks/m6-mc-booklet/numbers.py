# Every number in the Module 6 MC booklet (src/m6_mc_booklet/). HSC data sheet values.
from math import *
e, me, mp, mu0, g = 1.602e-19, 9.109e-31, 1.673e-27, 4*pi*1e-7, 9.8
k2 = mu0/(2*pi)   # 2e-7
D = radians
def p(l, x): print(f"  {l:46s} {x:.4g}")

print("== Topic 1")
print("Q3 E between plates: 250 V, 2.0 mm")
p("E", 250/2.0e-3); p("V*d", 250*2.0e-3); p("V/d with d in mm", 250/2.0); p("d/V", 2.0e-3/250)
print("Q4 proton 3.0e6 m/s in 0.20 T")
r = mp*3.0e6/(e*0.20); p("r", r); p("r with electron mass", me*3.0e6/(e*0.2)); p("qB/(mv)", 1/r); p("mv/(qB) with v^2", mp*9e12/(e*0.2))
print("Q12 electrons 4.0e6 m/s, 800 V over 2.0 mm")
E = 800/2.0e-3; p("E", E); p("B = E/v", E/4.0e6); p("v/E", 4.0e6/E)
print("Q14 electron accelerated through 2.0 kV")
v = sqrt(2*e*2000/me); p("v", v); p("no sqrt (v^2)", 2*e*2000/me); p("forgot 2", sqrt(e*2000/me)); p("proton mass", sqrt(2*e*2000/mp))
print("== Topic 2")
print("Q21 F/l: 2.0 A and 3.0 A, 0.50 m")
p("F/l", k2*2*3/0.5); p("mu0 I1 I2 / r", mu0*6/0.5); p("r not divided (x r)", k2*6*0.5); p("using r^2", k2*6/0.25)
print("Q23 l = 0.080 m, I = 3.0 A, B = 0.50 T, 40 deg")
p("F sin", 0.08*3*0.5*sin(D(40))); p("F cos", 0.08*3*0.5*cos(D(40))); p("F no angle", 0.08*3*0.5)
print("Q29 F = 0.024 N, l = 0.30 m, B = 0.040 T, 30 deg")
p("I sin", 0.024/(0.3*0.04*sin(D(30)))); p("I cos", 0.024/(0.3*0.04*cos(D(30)))); p("I no angle", 0.024/(0.3*0.04))
p("F*l*B*sin (multiplied)", 0.024*0.3*0.04*0.5)
print("Q30 wires 1.50 m, 3.0 mm, 30 A and 40 A, a = 0.050")
F = k2*30*40*1.5/3.0e-3; p("F", F); p("m", F/0.05); p("m using mm", k2*30*40*1.5/3.0/0.05); p("m forgot l", k2*30*40/3e-3/0.05)
p("m using 2*pi*1e-7", 2*pi*1e-7*30*40*1.5/3e-3/0.05)
print("== Topic 3")
print("Q37 flux: B = 0.40 T, A = 0.050 m^2, field at 30 deg to the PLANE (60 deg to the normal)")
p("BA cos60", 0.4*0.05*cos(D(60))); p("BA cos30", 0.4*0.05*cos(D(30))); p("BA", 0.4*0.05)
print("Q39 250 turns, A = 4.0e-3 m^2, B 0.60 -> 0 T in 0.050 s")
p("emf", 250*0.6*4e-3/0.05); p("N = 1", 0.6*4e-3/0.05); p("N dPhi (no /dt)", 250*0.6*4e-3); p("forgot area", 250*0.6/0.05)
print("Q46 rod 0.50 m at 2.0 m/s in 0.30 T, R = 1.5 ohm")
emf = 0.3*0.5*2.0; p("emf Blv", emf); p("I", emf/1.5); p("forgot v: Bl/R", 0.3*0.5/1.5); p("forgot l: Bv/R", 0.3*2/1.5); p("emf*R", emf*1.5)
print("Q48 240 V -> 12 V, Np = 1200")
p("Ns", 1200*12/240); p("inverse", 1200*240/12)
print("Q52 50 MW at 250 kV, line resistance 5.0 ohm")
I = 50e6/250e3; p("I", I); p("loss I^2 R", I*I*5); p("loss at 25 kV", (50e6/25e3)**2*5); p("V^2/R", 250e3**2/5); p("IR (volts)", I*5)
print("== Topic 4")
print("Q55 100 turns, 2.0 A, 0.010 m^2, 0.20 T, plane parallel to field")
p("tau", 100*2*0.01*0.2); p("n = 1", 2*0.01*0.2)
print("Q60 24 V motor, R = 2.0 ohm, I = 1.5 A")
p("back emf", 24-1.5*2); p("starting current", 24/2)
print("Q69 12 V, 2.5 A motor lifts 1.5 kg at 1.2 m/s")
pin, pout = 12*2.5, 1.5*g*1.2; p("Pin", pin); p("Pout", pout); p("eff %", 100*pout/pin); p("wasted %", 100-100*pout/pin); p("inverse %", 100*pin/pout)
print("Q70 50 turns, 0.020 m^2, 0.40 T, quarter turn in 0.025 s")
p("avg emf", 50*0.4*0.02/0.025); p("N = 1", 0.4*0.02/0.025); p("forgot area", 50*0.4/0.025); p("half (dt doubled)", 50*0.4*0.02/0.05)
