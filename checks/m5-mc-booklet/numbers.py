# Every number in the Module 5 MC booklet (src/m5_mc_booklet/).
from math import *
g, G, ME, rE = 9.8, 6.67e-11, 6.0e24, 6.371e6
GM = G*ME
def p(label, x): print(f"  {label:44s} {x:.4g}")
D = radians

print("== Topic 1: projectile motion")
print("Q3 kangaroo 9.0 m/s at 35 deg: speed at top")
p("u cos35", 9.0*cos(D(35))); p("u sin35", 9.0*sin(D(35)))
print("Q14 cannonball 40 m/s, max height 60 m: angle")
uy = sqrt(2*g*60); p("uy", uy); p("theta = asin(uy/u)", degrees(asin(uy/40)))
p("wrong: acos(uy/u)", degrees(acos(uy/40))); p("wrong: atan(60/40)", degrees(atan(60/40)))
print("Q16 horizontal launch, 30 deg below horizontal after 1.5 s")
vy = g*1.5; u = vy/tan(D(30)); p("vy", vy); p("u", u); p("speed", sqrt(u*u+vy*vy))
p("wrong vy/cos30", vy/cos(D(30)))
print("Q21 range 25 m/s at 40 deg, level ground")
u, th = 25, D(40); t = 2*u*sin(th)/g; p("t", t); p("range", u*cos(th)*t)
p("half range", u*cos(th)*t/2); p("range using sin for x", u*sin(th)*t)
p("u^2/g", u*u/g); p("range with t = u sin/g only", u*cos(th)*u*sin(th)/g)
print("Q22 max height 30 m/s at 50 deg")
u, th = 30, D(50); p("h", (u*sin(th))**2/(2*g)); p("u not uy", u*u/(2*g))
p("cos", (u*cos(th))**2/(2*g)); p("forgot 2", (u*sin(th))**2/g)
print("Q23 horizontal 12 m/s from 45 m cliff")
t = sqrt(2*45/g); p("t", t); p("range", 12*t); p("t no factor 2: sqrt(45/g)", sqrt(45/g)*12)
p("t = 45/12 then?", 45/12); p("range using t = sqrt(2*45*g)", 12*sqrt(2*45*g))
print("Q24 15 m/s at 30 deg up from 40 m cliff: time of flight")
uy = 15*sin(D(30)); t = (uy+sqrt(uy*uy+2*g*40))/g; p("t", t)
p("dropped from 40 m", sqrt(2*40/g)); p("time back to launch level", 2*uy/g)
p("using uy as -7.5 (launched down)", (-uy+sqrt(uy*uy+2*g*40))/g)

print("== Topic 2: circular motion")
print("Q26 torque 90 N m, 0.40 m, 60 deg")
p("F = tau/(r sin60)", 90/(0.40*sin(D(60)))); p("no angle", 90/0.40)
p("cos60", 90/(0.40*cos(D(60)))); p("tau*r*sin", 90*0.40*sin(D(60)))
print("Q29 5 laps in 8.0 s; time for 150 deg")
T = 8.0/5; p("T", T); p("t 150 deg", 150/360*T); p("t 210 deg", 210/360*T)
p("used 8.0 s as T", 150/360*8.0); p("deg not rad: 150/omega", 150/(2*pi/T))
print("Q30 150 g stopper, 0.80 m, 2.0 Hz")
m, r, f = 0.150, 0.80, 2.0; v = 2*pi*r*f; p("v", v); p("F", m*v*v/r)
p("omega = f", m*f*f*r); p("T = 2.0 s", m*(2*pi/2.0)**2*r); p("m in g", 150*v*v/r)
print("Q34 disc 0.50 m, 40 N at 25 deg to radius")
p("tau", 0.5*40*sin(D(25))); p("cos", 0.5*40*cos(D(25))); p("no angle", 0.5*40)
p("r in cm", 50*40*sin(D(25)))
print("Q36 F = 3.2 N, r = 0.60 m, omega = 3 pi")
w = 3*pi; p("m = F/(w^2 r)", 3.2/(w*w*0.6)); p("w not squared", 3.2/(w*0.6))
p("w = 3", 3.2/(9*0.6)); p("m = F r / w^2", 3.2*0.6/(w*w))
print("Q38 72 km/h on r = 120 m: banking angle")
v = 72/3.6; p("v", v); p("theta", degrees(atan(v*v/(120*g))))
p("inverse", degrees(atan(120*g/(v*v)))); p("km/h", degrees(atan(72**2/(120*g))))
p("not squared", degrees(atan(v/(120*g))))
print("Q44 loop r = 8.0 m: minimum speed at top")
p("sqrt(gr)", sqrt(g*8)); p("sqrt(2gr)", sqrt(2*g*8)); p("gr", g*8); p("sqrt(g/r)", sqrt(g/8))
print("Q45 1200 kg, friction 9600 N, r = 50 m")
p("v", sqrt(9600*50/1200)); p("v^2", 9600*50/1200); p("F/m*?", 9600/1200)
p("sqrt(F/(m r))", sqrt(9600/(1200*50)))
print("Q46 r = 0.30 m wheel at 120 rpm: rim speed")
w = 120*2*pi/60; p("omega", w); p("v", w*0.3); p("v using 120 as omega", 120*0.3)
p("v = 2 pi r f with f = 120", 2*pi*0.3*120); p("v using f = 2 Hz not 2 pi", 2*0.3)
print("Q47 0.50 kg, r = 1.2 m, 4.0 m/s: work by tension per rev")
F = 0.5*16/1.2; p("Fc", F); p("KE", 0.5*0.5*16); p("F*2 pi r", F*2*pi*1.2); p("F*r", F*1.2)

print("== Topic 3: gravity")
print("Q50 planet 5 M, 2.5 R", 5/2.5**2)
print("Q51 one mass x2, distance x3", 2/9)
print("Q52 g at 1000 km altitude")
r = rE+1.0e6; p("g", GM/r**2); p("h only", GM/1.0e6**2); p("1/r scaling", 9.8*rE/r)
p("r not squared", GM/r)
print("Q54 Mars T = 1.88 yr: a in AU")
p("a = T^(2/3)", 1.88**(2/3)); p("sqrt T", 1.88**0.5); p("T^1.5", 1.88**1.5); p("cbrt T", 1.88**(1/3))
print("Q55 satellite at 800 km: period")
r = rE+8.0e5; T = 2*pi*sqrt(r**3/GM); p("T s", T); p("T min", T/60)
p("T using rE (min)", 2*pi*sqrt(rE**3/GM)/60); p("T using h (min)", 2*pi*sqrt(8e5**3/GM)/60)
p("no sqrt T = 4pi^2 r^3/GM (s)", 4*pi**2*r**3/GM)
print("Q59 Titan: r = 1.22e9 m, T = 1.38e6 s")
r, T = 1.22e9, 1.38e6; p("M", 4*pi**2*r**3/(G*T**2)); p("no 4pi^2", r**3/(G*T**2))
p("T not squared", 4*pi**2*r**3/(G*T)); p("r^2", 4*pi**2*r**2/(G*T**2))
print("Q61 GPS 500 kg at 20 200 km altitude: U")
r = rE+2.02e7; m = 500; p("r", r); p("U", -GM*m/r); p("U with h", -GM*m/2.02e7)
p("U with rE", -GM*m/rE); p("E", -GM*m/(2*r))
print("Q62 KE of 2000 kg satellite at r = 8.0e6 m")
m, r = 2000, 8.0e6; p("K", GM*m/(2*r)); p("|U|", GM*m/r); p("E", -GM*m/(2*r))
p("K using v = sqrt(2GM/r)", 0.5*m*2*GM/r/1)  # same as |U|
p("K = GMm/r^2", GM*m/r**2)
print("Q65 Moon escape")
M, r = 7.35e22, 1.74e6; p("v_esc", sqrt(2*G*M/r)); p("v_orb", sqrt(G*M/r))
p("no sqrt", 2*G*M/r); p("r in km", sqrt(2*G*M/1.74e3))
print("Q66 4 M same R: 11.2 x 2", 11.2*2)
print("Q68 1000 kg: r1 = rE + 400 km to GEO")
m = 1000; r1 = rE+4.0e5; r2 = (GM*86400**2/(4*pi**2))**(1/3)
p("r1", r1); p("r2", r2); dE = GM*m/2*(1/r1-1/r2); p("dE", dE)
p("dU", GM*m*(1/r1-1/r2)); p("|E1|", GM*m/(2*r1)); p("|U1|", GM*m/r1); p("|E2|", GM*m/(2*r2))
print("Q70 800 N at r = 4 rE", 800/16, " r = 3rE:", 800/9)
print("Q71 a ratio r -> 4r", 16)
print("Q72 GEO speed")
r2 = (GM*86400**2/(4*pi**2))**(1/3); p("v GEO", 2*pi*r2/86400); p("v equator", 2*pi*rE/86400)
p("v LEO 400 km", sqrt(GM/(rE+4e5))); p("v_esc surface", sqrt(2*GM/rE))
